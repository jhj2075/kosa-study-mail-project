ALTER SESSION SET CURRENT_SCHEMA = MAIL_APP;

CREATE TABLE USERS
(
    USER_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LOGIN_ID   VARCHAR2(50)                           NOT NULL,
    PASSWORD   VARCHAR2(255)                          NOT NULL,
    USER_NAME  VARCHAR2(100)                          NOT NULL,
    EMAIL      VARCHAR2(255)                          NOT NULL,
    STATUS     VARCHAR2(20) DEFAULT 'ACTIVE'          NOT NULL,
    CREATED_AT TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP,
    CONSTRAINT UK_USERS_LOGIN_ID UNIQUE (LOGIN_ID),
    CONSTRAINT UK_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USERS_STATUS CHECK (STATUS IN ('ACTIVE', 'LOCKED', 'WITHDRAWN'))
);

CREATE TABLE EMAIL_RESERVATION
(
    EMAIL_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID          NUMBER                                 NOT NULL,
    SUBJECT          VARCHAR2(255)                          NOT NULL,
    CONTENT          CLOB,
    RECEIVER_EMAIL   VARCHAR2(255)                          NOT NULL,
    RESERVE_DATETIME TIMESTAMP                              NOT NULL,
    SENT_DATETIME    TIMESTAMP,
    STATUS           VARCHAR2(20) DEFAULT 'WAITING'         NOT NULL,
    CREATED_AT       TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT       TIMESTAMP,
    CONSTRAINT FK_EMAIL_RESERVATION_USER
        FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID),
    CONSTRAINT CK_EMAIL_RESERVATION_STATUS
        CHECK (STATUS IN
               ('WAITING', 'PROCESSING', 'QUEUED', 'SENDING', 'SENT', 'FAILED', 'CANCELED'))
);

CREATE TABLE EMAIL_QUEUE
(
    QUEUE_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMAIL_ID      NUMBER                                  NOT NULL,
    EXCHANGE_NAME VARCHAR2(100) DEFAULT 'mail.exchange'   NOT NULL,
    ROUTING_KEY   VARCHAR2(100) DEFAULT 'mail.send'       NOT NULL,
    MESSAGE_ID    VARCHAR2(100),
    PAYLOAD       CLOB                                    NOT NULL,
    STATUS        VARCHAR2(20)  DEFAULT 'PUBLISHED'       NOT NULL,
    PUBLISHED_AT  TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_EMAIL_QUEUE_RESERVATION
        FOREIGN KEY (EMAIL_ID) REFERENCES EMAIL_RESERVATION (EMAIL_ID),
    CONSTRAINT CK_EMAIL_QUEUE_STATUS
        CHECK (STATUS IN ('PUBLISHED', 'CONSUMED', 'FAILED', 'DEAD_LETTERED'))
);

CREATE TABLE EMAIL_SEND_LOG
(
    LOG_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMAIL_ID   NUMBER,
    QUEUE_ID   NUMBER,
    STATUS     VARCHAR2(20),
    MESSAGE    VARCHAR2(1000),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_EMAIL_SEND_LOG_RESERVATION
        FOREIGN KEY (EMAIL_ID) REFERENCES EMAIL_RESERVATION (EMAIL_ID),
    CONSTRAINT FK_EMAIL_SEND_LOG_QUEUE
        FOREIGN KEY (QUEUE_ID) REFERENCES EMAIL_QUEUE (QUEUE_ID),
    CONSTRAINT CK_EMAIL_SEND_LOG_STATUS
        CHECK (STATUS IN ('QUEUED', 'SENDING', 'SENT', 'FAILED', 'RETRY', 'DEAD_LETTERED'))
);

CREATE INDEX IX_EMAIL_RESERVATION_DUE
    ON EMAIL_RESERVATION (STATUS, RESERVE_DATETIME);

CREATE INDEX IX_EMAIL_RESERVATION_USER
    ON EMAIL_RESERVATION (USER_ID, CREATED_AT);

CREATE INDEX IX_EMAIL_QUEUE_EMAIL
    ON EMAIL_QUEUE (EMAIL_ID, PUBLISHED_AT);

CREATE INDEX IX_EMAIL_SEND_LOG_EMAIL
    ON EMAIL_SEND_LOG (EMAIL_ID, CREATED_AT);
